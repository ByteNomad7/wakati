-- Minimal stand-in for the parts of Supabase the migrations depend on, so they
-- can be applied and RLS-tested in an in-process Postgres (PGlite).
-- This is test infrastructure only; it is never applied to a real project.

create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;

create schema auth;
create table auth.users (
  id uuid primary key,
  email text,
  raw_user_meta_data jsonb not null default '{}'::jsonb
);

create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;

create schema storage;
create table storage.buckets (
  id text primary key, name text not null, public boolean default false,
  file_size_limit bigint, allowed_mime_types text[]
);
create table storage.objects (
  id uuid primary key default gen_random_uuid(),
  bucket_id text references storage.buckets (id), name text not null
);
alter table storage.objects enable row level security;
create function storage.foldername(name text) returns text[] language sql immutable as $$
  select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1];
$$;

grant usage on schema public, auth, storage to anon, authenticated, service_role;

-- Emulate a project with "auto-expose new tables" OFF: nothing created by the
-- migrations is reachable by the API roles unless the migrations grant it.
alter default privileges in schema public revoke execute on functions from public;
grant execute on function auth.uid() to anon, authenticated, service_role;
